#!/usr/bin/env node
// Wire the platform straight to your Power Automate flows. No proxy, no Cloudflare
// Worker, no Entra tenant.
//
//   node scripts/setup-endpoints.mjs                        prompt for each URL
//   node scripts/setup-endpoints.mjs --from ~/urls.env      read them from a file
//   node scripts/setup-endpoints.mjs --check                re-check what is configured
//
// The browser calls each signed flow URL directly, which is how this application worked
// before the proxy existed. It is the simplest thing that runs the real platform, and the
// trade is stated plainly below rather than left for you to discover.
//
// ─────────────────────────────────────────────────────────────────────────────
// WHAT GOING DIRECT COSTS
//
// A SAS-signed flow URL is a bearer credential. Wiring it here puts it in
// config/config.local.js and therefore into the browser, where anyone with the developer
// console — or anything that can read a network request — can take it and invoke that flow
// against the live registry, as anyone, from anywhere.
//
// That is the whole reason proxy/ exists: it holds the signatures server-side so no
// browser ever sees one, and it checks who is calling before forwarding.
//
// Going direct is the right call for getting the platform running, for development, and
// for a demonstration on a machine you control. It is not a posture to put real
// correspondence through on a shared or public deployment. Nothing here stops you; you
// should just know which one you are doing.
// ─────────────────────────────────────────────────────────────────────────────

import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline/promises';
import { fileURLToPath } from 'node:url';

import { EndpointKeys, EndpointContracts } from '../config/endpoints.config.js';
import { redact } from '../core/endpoint-registry.js';
import { readConfiguredEndpoints, run as runCheck, DERIVED_KEYS, CONFIGURABLE_KEYS } from './check-endpoints.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONFIG = path.join(ROOT, 'config', 'config.local.js');
const MARKER = 'GENERATED BY scripts/setup-endpoints.mjs';

const argv = process.argv.slice(2);
const flag = n => argv.includes(`--${n}`);
const value = n => { const i = argv.indexOf(`--${n}`); return i >= 0 ? argv[i + 1] : ''; };

/** Ordered so the endpoints the platform needs to boot come first. */
const GROUPS = [
  { title: 'Reads — the platform loads these on boot. Wire these first.',
    keys: ['FETCH_ALL', 'FETCH_ACTIVITIES', 'REFERENCE_DATA', 'GET_DOCS', 'FETCH_EMAIL_ATTACHMENTS'] },
  { title: 'Assignment', keys: ['SINGLE_ASSIGNMENT', 'BULK_ASSIGNMENT', 'BULK_ASSIGNMENT_DIRECT'] },
  { title: 'Governed writes', keys: ['DYNAMIC_ACTIONS', 'EMAIL', 'EMAIL_RELATED_TASK'] },
  { title: 'AI — optional; those surfaces degrade without them',
    keys: ['AI_EMAIL_ANALYSIS', 'AI_DOC_ANALYSIS', 'AI_CHAT'] },
  { title: 'Step-up confirmation', keys: ['OTP_GENERATE', 'OTP_VERIFY'] },
  { title: 'The multi-route flow', keys: ['SUBSIDIARY_ACTIONS'] },
];

/* DISPATCH_OUTBOUND and ARCHIVE_REFERENCE are real contracts but carry no URL of their
   own — both resolve to DYNAMIC_ACTIONS. Prompting for them would be asking twice for the
   same thing and inviting a mismatch, so they are excluded by DERIVED_KEYS rather than by
   being left off the group list, which would hide a genuinely forgotten endpoint.
   This asserts the two agree. */
const PROMPTED = new Set(GROUPS.flatMap(g => g.keys));
const unprompted = CONFIGURABLE_KEYS.filter(k => !PROMPTED.has(k));
if (unprompted.length) {
  console.error(`\n  setup-endpoints.mjs is out of date: ${unprompted.join(', ')} take a URL`);
  console.error('  but are in no prompt group. Add them to GROUPS.\n');
  process.exit(1);
}

// ---------------------------------------------------------------------------

function validate(url) {
  const raw = String(url || '').trim();
  if (!raw) return { ok: true, url: '' };
  let u;
  try { u = new URL(raw); } catch { return { ok: false, why: 'not a URL' }; }
  if (u.protocol !== 'https:') return { ok: false, why: 'must be https' };
  // Shape check only, and advisory: a signature is what makes a flow URL work, and a URL
  // without one will simply fail the connectivity check with a clear 401 rather than here.
  if (!u.searchParams.get('sig') && !u.searchParams.get('code')) {
    return { ok: true, url: raw, warn: 'no sig= or code= — is this the full trigger URL?' };
  }
  return { ok: true, url: raw };
}

/** KEY=value lines. Values are URLs and are never trimmed of their query string. */
function parseEnvFile(file) {
  const resolved = path.resolve(file.replace(/^~(?=$|\/)/, process.env.HOME || '~'));

  if (!fs.existsSync(resolved)) {
    throw new Error(`No such file: ${resolved}`);
  }
  // A filled-in copy inside the working tree is how a signature reaches a commit. The
  // example file ships with empty values, so this only ever fires on a real one.
  const inside = resolved.startsWith(ROOT + path.sep);
  const body = fs.readFileSync(resolved, 'utf8');
  const hasValues = /^\s*[A-Z_]+\s*=\s*\S/m.test(body);
  if (inside && hasValues) {
    throw new Error(
      `Refusing to read ${path.relative(ROOT, resolved)}: it holds signed URLs and it is\n` +
      `inside the repository. Move it out first —\n\n` +
      `    mv ${path.relative(ROOT, resolved)} ~/dgo-endpoints.env\n` +
      `    node scripts/setup-endpoints.mjs --from ~/dgo-endpoints.env\n`);
  }

  const out = {};
  body.split(/\r?\n/).forEach((line, i) => {
    const t = line.trim();
    if (!t || t.startsWith('#')) return;
    const eq = t.indexOf('=');
    if (eq < 0) throw new Error(`${resolved}:${i + 1} — expected KEY=url`);
    const key = t.slice(0, eq).trim().toUpperCase();
    const val = t.slice(eq + 1).trim().replace(/^["']|["']$/g, '');
    if (!val) return;
    if (!EndpointKeys.includes(key)) throw new Error(`${resolved}:${i + 1} — unknown endpoint "${key}"`);
    const v = validate(val);
    if (!v.ok) throw new Error(`${resolved}:${i + 1} — ${key}: ${v.why}`);
    out[key] = v.url;
  });
  return out;
}

async function promptForEndpoints(existing) {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  const collected = { ...existing };

  console.log('\nPaste each Power Automate trigger URL. Press Enter to skip one,');
  console.log('or type "done" to stop and write what you have.\n');
  if (Object.keys(existing).length) {
    console.log(`${Object.keys(existing).length} already configured — Enter keeps the current value.\n`);
  }

  outer:
  for (const group of GROUPS) {
    console.log(`\n── ${group.title}`);
    for (const key of group.keys) {
      const current = collected[key];
      const label = current ? `${key} [${redact(current)}]` : key;
      const answer = (await rl.question(`  ${label}\n  > `)).trim();

      if (answer.toLowerCase() === 'done') break outer;
      if (!answer) continue;

      const v = validate(answer);
      if (!v.ok) { console.log(`    ✗ ${v.why} — skipped`); continue; }
      if (v.warn) console.log(`    ! ${v.warn}`);
      collected[key] = v.url;
    }
  }
  rl.close();
  return collected;
}

// ---------------------------------------------------------------------------

function configFile(endpoints) {
  const lines = EndpointKeys
    .filter(k => endpoints[k])
    .map(k => `    ${JSON.stringify(k)}: ${JSON.stringify(endpoints[k])},`)
    .join('\n');

  return `/* ${MARKER} — do not commit.
 *
 * These are SAS-signed Power Automate trigger URLs. Each one authorises invoking its flow
 * by possession alone, and everything in this file is delivered to the browser. Treat it
 * exactly as you would a password file.
 *
 * .gitignore already covers config/config.local.js. Keep it that way.
 *
 * The platform talks to these flows DIRECTLY — no proxy, no Cloudflare Worker, no Entra
 * tenant. Verify them with:  node scripts/check-endpoints.mjs
 */
window.DGO_CONFIG = window.DGO_CONFIG || {
  endpoints: {
${lines}
  },

  auth: {
    /* FALSE, and it must stay false on this path.
     *
     * Turning it on routes every governed request through auth.proxyBaseUrl instead of at
     * the URLs above, and makes the client demand an Entra token — which is the proxy
     * deployment, not this one. Going direct means the platform runs in its development
     * posture: local profile, advisory RBAC, no token.
     *
     * So nothing here is ENFORCED. The flows are reachable by anyone holding a URL from
     * this file, and the platform's role checks are a UX affordance rather than a control.
     * That is the trade this path makes; proxy/ is what closes it.
     */
    enabled: false,
  },
};
`;
}

function writeConfig(endpoints, { force }) {
  if (fs.existsSync(CONFIG)) {
    const existing = fs.readFileSync(CONFIG, 'utf8');
    const generated = existing.includes(MARKER) || existing.includes('GENERATED BY scripts/dev-setup.mjs');
    if (!generated && !force) {
      console.log(`\n  config/config.local.js exists and was not written by a setup script.`);
      console.log(`  Left alone. Pass --force to replace it.\n`);
      return false;
    }
  }
  fs.mkdirSync(path.dirname(CONFIG), { recursive: true });
  fs.writeFileSync(CONFIG, configFile(endpoints), { mode: 0o600 });
  return true;
}

// ---------------------------------------------------------------------------

async function main() {
  if (flag('check')) process.exit(await runCheck());

  console.log('\n  Wiring the platform directly to Power Automate — no proxy.\n');

  const existing = readConfiguredEndpoints().endpoints;
  const from = value('from');

  let endpoints;
  if (from) {
    try {
      endpoints = { ...existing, ...parseEnvFile(from) };
    } catch (e) {
      console.error(`\n${e.message}\n`);
      process.exit(1);
    }
  } else if (process.stdin.isTTY) {
    endpoints = await promptForEndpoints(existing);
  } else {
    console.error('Nothing to read: not a terminal, and no --from <file> given.');
    console.error('  cp scripts/endpoints.example.env ~/dgo-endpoints.env');
    console.error('  node scripts/setup-endpoints.mjs --from ~/dgo-endpoints.env\n');
    process.exit(1);
  }

  const count = CONFIGURABLE_KEYS.filter(k => endpoints[k]).length;
  if (!count) {
    console.log('\n  No URLs given — nothing written.\n');
    process.exit(1);
  }

  if (!writeConfig(endpoints, { force: flag('force') })) process.exit(1);

  console.log(`\n  ✓ ${count}/${CONFIGURABLE_KEYS.length} configured  →  config/config.local.js (git-ignored, 0600)`);
  if (endpoints.DYNAMIC_ACTIONS && DERIVED_KEYS.length) {
    console.log(`    ${DERIVED_KEYS.join(' and ')} route through DYNAMIC_ACTIONS — no separate URL needed.`);
  }

  if (from) {
    console.log(`\n  Delete ${from} when you are done with it. It is a credential file.`);
  }

  if (flag('no-check')) {
    console.log('\n  Skipped the connectivity check (--no-check).');
    console.log('  Run it later:  node scripts/check-endpoints.mjs\n');
    return;
  }

  const failed = await runCheck();

  console.log('  Serve the platform:  npx http-server . -p 8080 --cors -c-1');
  console.log('  Then open:           http://localhost:8080/\n');

  process.exit(failed);
}

await main();
